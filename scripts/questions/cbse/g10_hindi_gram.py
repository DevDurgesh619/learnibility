def va_which(r):
    target = r.choice(['कर्मवाच्य', 'भाववाच्य', 'कर्तृवाच्य'])
    good, bad = None, []
    for _ in range(60):
        s, v = _mixed_sentence(r)
        if v == target and good is None:
            good = s
        elif v != target and len(bad) < 3 and s not in bad:
            bad.append(s)
        if good and len(bad) == 3:
            break
    _need(good and len(bad) == 3)
    return mcq(f'निम्नलिखित में से {target} का उदाहरण कौन-सा है?', good, bad, f'"{good}"—{VWHY[target]}', r)


