def fem(pf):
    if pf == 'किया':
        return 'की'
    if pf.endswith('या'):
        return pf[:-2] + 'ई'
    return pf[:-1] + 'ी'


def _vachya_forms(r):
    """All three tenses of one कर्तृवाच्य / कर्मवाच्य pair: {tense: (कर्तृ, कर्म)}, plus wrong-agreement कर्म forms."""
    root, pf, fut, objs = r.choice(TV)
    obj, og = r.choice(objs)
    nm, girl = person(r)
    pfo = fem(pf) if og == 'f' else pf
    pfo_w = pf if og == 'f' else fem(pf)
    m_, f_ = (og == 'm'), (og == 'f')
    forms = {
        'past': (f'{nm} ने {obj} {pfo}।', f'{nm} द्वारा {obj} {pfo} {"गई" if f_ else "गया"}।',
                 f'{nm} द्वारा {obj} {pfo_w} {"गया" if f_ else "गई"}।'),
        'pres': (f'{nm} {obj} {root}{"ती" if girl else "ता"} है।', f'{nm} द्वारा {obj} {pfo} {"जाती" if f_ else "जाता"} है।',
                 f'{nm} द्वारा {obj} {pfo_w} {"जाता" if f_ else "जाती"} है।'),
        'fut': (f'{nm} {obj} {fut}{"गी" if girl else "गा"}।', f'{nm} द्वारा {obj} {pfo} {"जाएगी" if f_ else "जाएगा"}।',
                f'{nm} द्वारा {obj} {pfo_w} {"जाएगा" if f_ else "जाएगी"}।'),
    }
    return forms, (obj, og), nm


def _vachya_pair(r):
    """(कर्तृवाच्य, कर्मवाच्य, three wrong कर्म forms, tense, (obj, gender))."""
    forms, og, nm = _vachya_forms(r)
    t = r.choice(list(forms))
    k, m, mw = forms[t]
    wrong = [mw] + [forms[x][1] for x in forms if x != t]
    return k, m, wrong, t, og


def va_to_kartri_gen(r):
    forms, og, nm = _vachya_forms(r)
    t = r.choice(list(forms))
    k, m, _ = forms[t]
    wrong = [forms[x][0] for x in forms if x != t] + [k.replace(f'{nm} ', f'{nm} से ', 1) if ' ने ' not in k else k.replace(' ने ', ' से ')]
    return k, m, wrong


def _bhav_pair(r):
    root, pf, adv = r.choice(IV)
    nm, girl = person(r)
    past = r.random() < 0.5
    if past:
        k = f'{nm} {adv} नहीं {root} {"सकी" if girl else "सका"}।'
        b = f'{nm} से {adv} {pf} नहीं गया।'
        wrong = [f'{nm} से {adv} {fem(pf)} नहीं गई।' if girl else f'{nm} द्वारा {adv} {pf} नहीं गया।',
                 f'{nm} ने {adv} नहीं {pf}।', f'{nm} से {adv} {pf} नहीं जाता।']
    else:
        k = f'{nm} {adv} नहीं {root} {"सकती" if girl else "सकता"}।'
        b = f'{nm} से {adv} {pf} नहीं जाता।'
        wrong = [f'{nm} से {adv} {fem(pf)} नहीं जाती।' if girl else f'{nm} द्वारा {adv} {pf} नहीं जाता।',
                 f'{nm} {adv} {pf} नहीं जाता।', f'{nm} से {adv} {pf} नहीं गया।']
    return k, b, wrong


def va_to_karm(r):
    k, m, wrong, _, (obj, og) = _vachya_pair(r)
    return mcq(f'"{k}"—इस वाक्य का कर्मवाच्य रूप है—', m, wrong,
               f'कर्मवाच्य: "{m}"। कर्ता के साथ "द्वारा", क्रिया का लिंग-वचन कर्म "{obj}" ({"स्त्रीलिंग" if og == "f" else "पुल्लिंग"}) के अनुसार, काल वही।', r)


def va_to_bhav(r):
    k, b, wrong = _bhav_pair(r)
    return mcq(f'"{k}"—इस वाक्य का भाववाच्य रूप है—', b, wrong,
               f'भाववाच्य: "{b}"। कर्ता के साथ "से"; क्रिया अकर्मक, सदा अन्य पुरुष, पुल्लिंग, एकवचन में।', r)


def va_to_kartri(r):
    k, m, wrong = va_to_kartri_gen(r)
    nm = k.split()[0]
    return mcq(f'"{m}"—इस वाक्य का कर्तृवाच्य रूप है—', k, wrong, f'कर्तृवाच्य: "{k}"—कर्ता "{nm}" प्रधान है; काल वही रहता है।', r)


def _mixed_sentence(r):
    """(sentence, vachya)."""
    t = r.random()
    if t < 0.36:
        k, m, _, _, _ = _vachya_pair(r)
        return k, 'कर्तृवाच्य'
    if t < 0.7:
        k, m, _, _, _ = _vachya_pair(r)
        return m, 'कर्मवाच्य'
    k, b, _ = _bhav_pair(r)
    return b, 'भाववाच्य'


