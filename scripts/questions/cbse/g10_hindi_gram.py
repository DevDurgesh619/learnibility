_CYC: dict = {}


def cp(key, r, seq):
    return _CYC.setdefault(key, Cycler('g10g_' + key)).pick(r, list(seq))


def table_set(make_part, k, head, each=1):
    """k parts from make_part(r) -> (question, answer) as one निर्देशानुसार item (own copy of the g8 helper,
    without the doubled danda at the end of the key)."""
    def gen(r):
        seen, parts, guard = set(), [], 0
        while len(parts) < k and guard < 60:
            guard += 1
            q, a = make_part(r)
            if q in seen or any(a in pq or pa in q or pa == a for pq, pa in parts):
                continue
            seen.add(q)
            parts.append((q, a))
        if len(parts) < k:
            raise ValueError('not enough parts')
        stem = head + '\n' + '\n'.join(f'({ROMAN[i]}) {q}' for i, (q, _) in enumerate(parts))
        ans = '; '.join(f'({ROMAN[i]}) {a.rstrip("।")}' for i, (_, a) in enumerate(parts))
        return {'stem': stem, 'answer': ans, 'key': f'प्रत्येक भाग {each} अंक (कुल {k * each} अंक)। {ans}।'}
    return gen


def _need(c):
    if not c:
        raise ValueError('no item')


def ar_family(rows):
    """rows: (A, R, code, why)."""
    def g(r):
        a, rsn, code, why = r.choice(rows)
        return har(a, rsn, code, why)
    return g


def fact_mcq(rows):
    def g(r):
        q, a, w, key = r.choice(rows)
        w = r.sample(list(w), 3) if len(w) > 3 else list(w)
        return mcq(q, a, w, key, r)
    return g


def wr_fam(rows, marks=2):
    def g(r):
        q, a = r.choice(rows)
        return {'stem': q, 'answer': a, 'key': f'मूल्य-बिंदु: {a} ({marks} अंक)', 'marks': marks}
    return g


