def gram_families(spec, ch, grade):
    e = spec['engine']
    if e == 'vakya':
        return vakya_families()
    if e == 'vachya':
        return vachya_families()
    if e == 'pad':
        return pad_families()
    if e == 'alank':
        return alank_families(spec.get('types'), spec.get('examples', ()))
    raise SystemExit(f'unknown grammar engine {e}')


