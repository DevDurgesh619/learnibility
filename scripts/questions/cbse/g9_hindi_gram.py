def ok_pair(a, b):
    return a != b and not any(a in c and b in c for c in SAME)


def muh_meaning(r):
    m, a = cp('9muh_meaning', r, MUH)
    return mcq(f'"{m}" मुहावरे का सही अर्थ क्या है?', a, r.sample([x for x in MUH_A if ok_pair(x, a) and ok_pair(x, m)], 3), f'"{m}" का अर्थ है—{a}।', r)


def muh_which(r):
    m, a = cp('9muh_which', r, MUH)
    return mcq(f'"{a}" अर्थ के लिए उपयुक्त मुहावरा चुनिए।', m, r.sample([x for x in MUH_M if ok_pair(x, m)], 3), f'"{a}" के लिए मुहावरा: {m}।', r)


def muh_fill(r):
    s, m, form = cp('9muh_fill', r, MUH_CTX)
    wrong = r.sample(sorted({c[1] for c in MUH_CTX if ok_pair(c[1], m)}), 3)
    return mcq(f'रिक्त स्थान के लिए उचित मुहावरा चुनिए: "{s} ______।"', m, wrong, f'प्रसंग के अनुसार: "{s} {form}।"', r)


def lok_meaning(r):
    m, a = cp('9lok_meaning', r, LOK)
    return mcq(f'"{m}"—इस लोकोक्ति का अर्थ क्या है?', a, r.sample([x[1] for x in LOK if x[0] != m and ok_pair(x[1], a)], 3), f'लोकोक्ति "{m}" का अर्थ: {a}।', r)


