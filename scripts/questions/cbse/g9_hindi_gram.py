def muh_part(r):
    k = r.random()
    if k < 0.45:
        m, a = r.choice(MUH)
        return f'"{m}" मुहावरे का अर्थ लिखिए।', a
    if k < 0.8:
        s, m, form = r.choice(MUH_CTX)
        return f'उचित मुहावरे से रिक्त स्थान भरिए: "{s} ______।"', form
