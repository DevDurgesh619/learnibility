def up_part(r):
    k = r.random()
    if k < 0.35:
        u, b, w = r.choice(UPS)
        return f'उपसर्ग और मूल शब्द अलग कीजिए: {w}', f'{u} + {b}'
    if k < 0.7:
        b, p, w = r.choice(PRAT)
        return f'मूल शब्द और प्रत्यय अलग कीजिए: {w}', f'{b} + {p}'
    if k < 0.85:
        u, b, w = r.choice(UPS)
        return f'"{u}" उपसर्ग जोड़कर शब्द बनाइए: {b}', w
    b, p, w = r.choice(PRAT)
    return f'"{p}" प्रत्यय जोड़कर शब्द बनाइए: {b}', w


