def kavya_gen():
    from g8_hindi_lib import shuffled, opts_line, ROMAN

    def gen(r):
        k = r.choice(KAVYA)
        qs = r.sample(k['qs'], 4)
        lines = ['निम्नलिखित काव्यांश को ध्यानपूर्वक पढ़कर पूछे गए प्रश्नों के उत्तर दीजिए।', k['text']]
        ans = []
        for j, (q, a, wrong) in enumerate(qs):
            opts, L = shuffled(r, a, wrong)
            lines.append(f'({ROMAN[j]}) {q}\n{opts_line(opts)}')
            ans.append(f'({ROMAN[j]}) ({L}) {a}')
        t, bad = k['title']
        opts, L = shuffled(r, t, bad)
        lines.append(f'(v) काव्यांश का उपयुक्त शीर्षक है—\n{opts_line(opts)}')
        ans.append(f'(v) ({L}) {t}')
        lines.append(f'(vi) {k["written"][0]}')
        ans.append(f'(vi) {k["written"][1]}')
        return {'stem': '\n'.join(lines), 'answer': ' '.join(ans),
                'key': '(i)–(v) प्रत्येक 1 अंक; (vi) 2 अंक। कुल 7 अंक। ' + ' '.join(ans)}
    return gen
