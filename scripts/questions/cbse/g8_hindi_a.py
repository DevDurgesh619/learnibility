def tuk_mcq(r):
    w = cp('tuk_mcq', r, list(TUK))
    good = r.choice(TUK[w])
    wrong = r.sample([x for k, v in TUK.items() if k != w for x in v], 3)
    return mcq(f'"{w}" शब्द का तुकांत शब्द कौन-सा है?', good, wrong, f'"{w}" और "{good}" के अंत की ध्वनि समान है।', r)


