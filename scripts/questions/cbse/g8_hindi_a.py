def letter_parts(r):
    t = r.choice(['औपचारिक', 'अनौपचारिक'])
    rows = {'औपचारिक': [('संबोधन', 'महोदय/महोदया'), ('समापन', 'भवदीय/आपका आज्ञाकारी शिष्य'), ('विषय', 'पत्र के विषय का संक्षिप्त उल्लेख')],
            'अनौपचारिक': [('संबोधन', 'पूज्य पिताजी/प्रिय मित्र'), ('समापन', 'आपका प्यारा पुत्र/तुम्हारा मित्र'), ('अभिवादन', 'सादर प्रणाम/सस्नेह नमस्ते')]}
    part, ans = r.choice(rows[t])
    wrong_pool = {'महोदय/महोदया': ['प्रिय मित्र', 'पूज्य माताजी', 'प्यारे भैया'], 'भवदीय/आपका आज्ञाकारी शिष्य': ['तुम्हारा मित्र', 'तुम्हारी प्यारी बहन', 'ढेर सारा प्यार'],
                  'पत्र के विषय का संक्षिप्त उल्लेख': ['कुशल-क्षेम का प्रश्न', 'प्रेषक का पूरा पता', 'छुट्टियों का वर्णन'],
                  'पूज्य पिताजी/प्रिय मित्र': ['महोदय', 'सेवा में', 'मान्यवर संपादक जी'], 'आपका प्यारा पुत्र/तुम्हारा मित्र': ['भवदीय', 'प्रार्थी', 'आपका विश्वासपात्र'],
                  'सादर प्रणाम/सस्नेह नमस्ते': ['विषय:', 'सेवा में', 'सविनय निवेदन है']}
    return mcq(f'{t} पत्र में "{part}" के लिए उपयुक्त रूप कौन-सा है?', ans, wrong_pool[ans], f'{t} पत्र में {part}: {ans}।', r)


