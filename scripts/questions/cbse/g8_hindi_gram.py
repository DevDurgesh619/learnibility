def syn_mcq(r):
    w = cp('syn_mcq', r, list(SYN))
    good = r.choice(SYN[w])
    others = [s for k, v in SYN.items() if k != w for s in v]
    return mcq(f'"{w}" शब्द का पर्यायवाची शब्द कौन-सा है?', good, r.sample(others, 3),
               f'"{good}" का अर्थ भी "{w}" है; बाकी विकल्प दूसरे शब्दों के पर्यायवाची हैं।', r)


def syn_not(r):
    w = cp('syn_not', r, [k for k, v in SYN.items() if len(v) >= 3])
    good = r.sample(SYN[w], 3)
    odd_k = r.choice([k for k in SYN if k != w])
    odd = r.choice(SYN[odd_k])
    return mcq(f'निम्नलिखित में से कौन-सा शब्द "{w}" का पर्यायवाची नहीं है?', odd, good,
               f'"{odd}" "{odd_k}" का पर्यायवाची है; {", ".join(good)} "{w}" के पर्यायवाची हैं।', r)


def syn_two(r):
    w = cp('syn_two', r, [k for k, v in SYN.items() if len(v) >= 2])
    a, b = SYN[w][:2]
