def ant_mcq(r):
    a, b = cp('ant_mcq', r, ANT)
    if r.random() < 0.5:
        a, b = b, a
    wrong = r.sample([x for x in ANT_WORDS if x not in (a, b)], 3)
    return mcq(f'"{a}" शब्द का विलोम शब्द कौन-सा है?', b, wrong, f'"{a}" का उल्टा अर्थ देने वाला शब्द "{b}" है।', r)


