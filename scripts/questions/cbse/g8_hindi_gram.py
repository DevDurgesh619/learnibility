def anup_letter(r):
    pairs = [('चारु चंद्र की चंचल किरणें', 'च'), ('तरनि तनूजा तट तमाल तरुवर बहु छाए', 'त'), ('मुदित महीपति मंदिर आए', 'म'),
             ('बंधन बाँधे बहुत बड़े', 'ब'), ('रघुपति राघव राजा राम', 'र')]
