            q = (f'यह अंश जिस {t["kind"]} से लिया गया है, उसका मुख्य उद्देश्य क्या है?' if j == 1 else
                 f'यह अंश जिस {t["kind"]} से लिया गया है, उसके मुख्य {who} कौन हैं?')
            return mcq(rng, f'{lead2(t)}\n\n{window(rng, t)}\n\n{q}', right, rng.sample(pool, 3),
                       f'पूरे {"श्रव्य अंश" if lis else "पाठ"} के विषय और भाषा से स्पष्ट है: {right}।')

