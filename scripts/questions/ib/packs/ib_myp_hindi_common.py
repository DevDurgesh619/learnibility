def excerpt(body, probe, width=3, ans=''):
    """The sentences of body around the one that best matches the answer (weighted) and the question."""
    parts = [x.strip() for x in re.split(r'(?<=[।?!])\s+|\n', body) if x.strip()]
    if len(parts) <= width:
        return body
    # Answers that quote the text in several places need every quoted sentence on screen.
    quoted = [q.strip(' .…!?।') for q in re.findall(r'“([^”]{4,})”', ans)]
    idx = sorted({i for q in quoted for i, x in enumerate(parts) if q[:14] and q[:14] in x})
    if len(idx) >= 2 and idx[-1] - idx[0] < 11:
        lo = max(0, min(idx[0], len(parts) - width))
        hi = max(idx[-1] + 1, lo + width)
        return ' '.join(parts[lo:hi])
    pt, at = _stems(probe), _stems(ans)
    best = max(range(len(parts)), key=lambda i: (3 * len(_stems(parts[i]) & at) + len(_stems(parts[i]) & pt), -i))
    lo = max(0, min(best - 1, len(parts) - width))
    return ' '.join(parts[lo:lo + width])


