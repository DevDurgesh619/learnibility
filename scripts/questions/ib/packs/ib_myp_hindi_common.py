# Duplicate guard mirroring scripts/questions/validate.ts (normaliseStem + 3-gram Jaccard >= 0.85
# within a chapter, MCQ options included). The engine's own filter splits Devanagari words at the
# vowel signs, so it can pass stems that the validator rejects; this guard drops those draws.
