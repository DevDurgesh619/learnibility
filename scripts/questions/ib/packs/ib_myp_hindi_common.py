def g_viram(bank, marks_bank, name='g_viram'):
    """bank: (unpunctuated, punctuated, rule); marks_bank: (name, sign)."""
    def gen(kit, key, th):
        def fn(rng, slot):
            raw, ok, rule = rng.choice(bank)
            return dict(stem=f'उचित विराम-चिह्न लगाकर वाक्य फिर से लिखिए:\n“{raw}”', answer=ok, type='short', marks=2,
                        markingKey=f'{ok} — 2 अंक सभी चिह्न सही होने पर, 1 अंक एक चिह्न छूटने पर। नियम: {rule}')
        kit.add(key, 'C3', (1, 4), fn, 'short', None, name)

        def nm(rng, slot):
            n, s = rng.choice(marks_bank)
            others = [x[0] for x in marks_bank if x[0] != n]
            return mcq(rng, f'विराम-चिह्न ‘{s}’ का नाम क्या है?', n, rng.sample(others, 3), f'‘{s}’ — {n}।')
        kit.add(key, 'C1', (1, 2), nm, 'mcq', None, name + '_nm')

        def why(rng, slot):
            raw, ok, rule = rng.choice(bank)
            return dict(stem=f'“{ok}” — इस वाक्य में विराम-चिह्नों का प्रयोग क्यों किया गया है? नियम स्पष्ट कीजिए और बताइए कि इनके बिना अर्थ में क्या कठिनाई होती।',
                        answer=f'{rule} बिना चिह्नों के वाक्य पढ़ने में अस्पष्ट होता और अर्थ बदल सकता था।', type='explain', marks=2,
                        markingKey=f'1 अंक नियम: {rule}; 1 अंक अर्थ/स्पष्टता पर प्रभाव।')
        kit.add(key, 'C2', (1, 4), why, 'explain', None, name + '_why')
    return gen
