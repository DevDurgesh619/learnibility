def g_vakya(bank, name='g_vakya'):
    """bank: (सरल, संयुक्त, मिश्र) rows."""
    L = VAKYA_LABELS

    def gen(kit, key, th):
        def ident(rng, slot):
            row = rng.choice(bank)
            j = rng.randrange(3)
            return mcq(rng, f'रचना के आधार पर वाक्य का भेद पहचानिए:\n“{row[j]}”', L[j], [l for k, l in enumerate(L) if k != j] + ['विधानवाचक वाक्य' if j else 'प्रश्नवाचक वाक्य'],
                       f'“{row[j]}” — {L[j]}। {VAKYA_WHY[j]}')
        kit.add(key, 'C1', (1, 3), ident, 'mcq', None, name + '_id')

        def tr(rng, slot):
            row = rng.choice(bank)
            i, j = rng.sample(range(3), 2)
            return dict(stem=f'निर्देशानुसार वाक्य बदलिए — {L[j]} में:\n“{row[i]}”', answer=row[j], type='short', marks=2,
                        markingKey=f'{row[j]} — 1 अंक सही संयोजक/संबंधवाचक शब्द ({VAKYA_WHY[j]}), 1 अंक अर्थ बदले बिना शुद्ध वाक्य। अन्य शुद्ध रूप भी मान्य।')
        kit.add(key, 'C3', (1, 4), tr, 'short', None, name + '_tr')

