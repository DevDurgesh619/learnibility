STOP = set('का की के को में से है हैं था थी थे और पर भी तो यह वह ये वे एक कि ने नहीं कर रहा रही रहे हो गया गई गए अपने अपनी इस उस लिए साथ जो क्या क्यों कैसे कौन कौन-से कौन-सा कौन-सी पाठ अनुसार लेखक बताइए लिखिए दीजिए कीजिए समझाइए किस किसी'.split())


def _toks(s):
    return {w for w in re.findall(r'[ऀ-ॿ]+(?:-[ऀ-ॿ]+)?|\d+', s) if len(w) > 2 and w not in STOP}


def _stems(s):
    """Loose stems for matching inflected forms: each hyphen part cut to its first four code points."""
    out = set()
    for w in _toks(s):
        for p in w.split('-'):
            if len(p) > 2 and p not in STOP:
                out.add(p[:4])
    return out


