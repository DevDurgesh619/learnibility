    def tasks(self, key, th, focus='', d=(4, 5), tt=None, lang=False):
        """Theme-based writing tasks (style 'wr') for every subtopic; criteria C and D.
        The subtopic focus is shown only where it fits the task: same text type, or a language focus."""
        cn = th['name']
        own = focus
        alt = GEN_FOCUS[int(re.sub(r'\D', '', key.split('-st')[-1]) or 1) % len(GEN_FOCUS)]

        want = tt

        def wt(rng, slot):
            sit, tt, bl = rng.choice([x for x in th['tasks'] if x[1] not in SHORT_WORDS] or th['tasks'])
            focus = own if (lang or want is None or tt == want) else alt
            nm = TT[tt]['name']
            m = slot.marks or 12
            w = self.words_long if slot.set == 'mock' else self.words
            if rng.random() < 0.5:
                stem = f'{sit}\nइस स्थिति के लिए एक {nm} लिखिए। अपने उत्तर में:\n{_bul(bl)}\n{focus}\nशब्द-सीमा: {w}।'
            else:
                stem = f'लेखन कार्य (विषय: {cn})\n{sit}\nउपयुक्त प्रारूप में {nm} लिखिए और इन बिंदुओं को शामिल कीजिए — {"; ".join(bl)}। {focus} ({w})'
            ans = (f'अपेक्षित उत्तर: {nm} की परंपराएँ — {"; ".join(TT[tt]["conv"][:3])}। विषय-वस्तु — {"; ".join(bl)}। '
                   f'रजिस्टर — {TT[tt]["reg"]}; पाठक — {TT[tt]["aud"]}।')
            return dict(stem=re.sub(r'\n+', '\n', stem), answer=ans, markingKey=wr_key(m, self.phase), type='long', marks=m,
                        minutes=35 if slot.set == 'mock' else 25)
        self.add(key, 'C4', d, wt, 'long', 'wr', 'wr_task')

    def writing(self, key, th, tt, tasks):
        """Text-type subtopic: tasks = [(situation, [bullets])] for this text type."""
        cn = th['name']
        X = TT[tt]
        nm = X['name']
        near = SIMILAR + [{'ब्लॉग प्रविष्टि', 'भाषण'}, {'लेख', 'निबंध'}, {'भाषण', 'लेख'}]
        others = [k for k, v in TT.items() if v['grp'] != X['grp'] and not any({X['name'], v['name']} <= g for g in near)]

        def conv_yes(rng, slot):
            sit, bl = rng.choice(tasks)
            c = rng.choice(X['conv'])
            w = [rng.choice(TT[k]['conv']) for k in rng.sample(others, 3)]
            return mcq(rng, f'स्थिति: {sit}\nइस {nm} के प्रारूप में निम्नलिखित में से कौन-सी विशेषता सबसे उपयुक्त होगी?', c, w,
                       f'{nm} की एक प्रमुख परंपरा है — {c}। बाकी विकल्प दूसरे पाठ-प्रकारों की विशेषताएँ हैं।')
        self.add(key, 'C1', (1, 3), conv_yes, 'mcq', None, 'w_conv')

        def conv_no(rng, slot):
            sit, bl = rng.choice(tasks)
            right = rng.sample(X['conv'], 3)
            k = rng.choice(others)
            wrong = rng.choice(TT[k]['conv'])
            return mcq(rng, f'‘{cn}’ विषय पर {nm} लिखते समय निम्नलिखित में से कौन-सी विशेषता इस पाठ-प्रकार के लिए उपयुक्त नहीं है?\n(संदर्भ: {sit})',
                       wrong, right, f'‘{wrong}’ — यह {TT[k]["name"]} की विशेषता है, {nm} की नहीं।')
        self.add(key, 'C1', (2, 3), conv_no, 'mcq', None, 'w_convno')

        def register(rng, slot):
            sit, bl = rng.choice(tasks)
            return dict(stem=f'स्थिति: {sit}\nइस {nm} के लिए कैसी भाषा और लहजा उपयुक्त होगा? पाठक और उद्देश्य का उल्लेख करते हुए समझाइए।',
                        answer=f'रजिस्टर: {X["reg"]}। पाठक: {X["aud"]}। कारण: पाठक से संबंध और उद्देश्य ({bl[0]}) के अनुसार भाषा का स्तर तय होता है।',
                        type='explain', marks=3, markingKey=f'1 अंक उपयुक्त रजिस्टर ({X["reg"]}); 1 अंक पाठक की पहचान ({X["aud"]}); 1 अंक उद्देश्य से जोड़कर कारण (मानदंड C)।')
        self.add(key, 'C2', (2, 4), register, 'explain', None, 'w_reg')

        def why_conv(rng, slot):
            sit, bl = rng.choice(tasks)
            a, b = rng.sample(X['conv'], 2)
            return dict(stem=f'स्थिति: {sit}\nइस कार्य के लिए {nm} में (क) {a} और (ख) {b} क्यों आवश्यक हैं? प्रत्येक का पाठक पर प्रभाव समझाइए।',
                        answer=f'(क) {a} — इससे पाठ-प्रकार तुरंत पहचाना जाता है और पाठक को संदर्भ मिलता है। (ख) {b} — इससे उद्देश्य पूरा होता है और पाठक जुड़ाव महसूस करता है।',
                        type='explain', marks=4, markingKey='प्रत्येक विशेषता के लिए 2 अंक: 1 अंक कार्य/उद्देश्य बताने पर, 1 अंक पाठक पर प्रभाव से जोड़ने पर (मानदंड C — संप्रेषण)।')
        self.add(key, 'C2', (2, 4), why_conv, 'explain', None, 'w_why')

        def opening(rng, slot):
            sit, bl = rng.choice(tasks)
            return dict(stem=f'स्थिति: {sit}\nइस {nm} का केवल आरंभिक भाग (40–60 शब्द) लिखिए, जिसमें पाठ-प्रकार की आरंभिक परंपराएँ स्पष्ट हों।',
                        answer=f'अपेक्षित: {X["conv"][0]}; विषय का परिचय ({bl[0]}); {X["reg"]}।', type='short', marks=4,
                        markingKey=f'2 अंक: आरंभ की परंपराएँ ({X["conv"][0]}); 1 अंक: विषय का स्पष्ट परिचय; 1 अंक: उपयुक्त रजिस्टर और शुद्ध भाषा।')
        self.add(key, 'C3', (2, 4), opening, 'short', None, 'w_open')

        def closing(rng, slot):
            sit, bl = rng.choice(tasks)
            return dict(stem=f'स्थिति: {sit}\nइस स्थिति पर आपने {nm} का मुख्य भाग लिख लिया है। अब इसका समापन (30–50 शब्द) लिखिए, जो पाठ-प्रकार और उद्देश्य के अनुरूप हो।',
                        answer=f'अपेक्षित: मुख्य संदेश का सार ({bl[-1]}), पाठ-प्रकार के अनुरूप समापन ({CLOSE.get(tt, X["conv"][2])}), {X["reg"]}।', type='short', marks=3,
                        markingKey='1 अंक: मुख्य संदेश का सार; 1 अंक: पाठ-प्रकार के अनुरूप समापन की परंपरा; 1 अंक: उपयुक्त लहजा और शुद्ध भाषा।')
        self.add(key, 'C3', (2, 4), closing, 'short', None, 'w_close')

        def plan(rng, slot):
            sit, bl = rng.choice(tasks)
            return dict(stem=f'स्थिति: {sit}\nइस {nm} की रूपरेखा बनाइए: शीर्षक/संबोधन, तीन मुख्य {"बिंदु" if tt in SHORT_WORDS else "अनुच्छेदों के विचार (प्रत्येक के साथ एक उदाहरण)"} और समापन।',
                        answer=f'अपेक्षित रूपरेखा: {X["conv"][0]}; {"बिंदु" if tt in SHORT_WORDS else "अनुच्छेद"} — {"; ".join(bl)}; समापन — {CLOSE.get(tt, X["conv"][2])}।', type='short', marks=5,
                        markingKey='5 अंक: पाठ-प्रकार के अनुरूप आरंभ (1), तीन प्रासंगिक और तार्किक क्रम वाले बिंदु (3), समापन (1)।')
        self.add(key, 'C3', (3, 5), plan, 'short', None, 'w_plan')

        def develop(rng, slot):
            sit, bl = rng.choice(tasks)
            b = rng.choice(bl)
