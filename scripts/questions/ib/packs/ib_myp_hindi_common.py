import sys as _sys
import unicodedata as _ud

_SEEN: dict = {}


def _jsnorm(s):
    s = _ud.normalize('NFKC', s).lower()
    s = re.sub(r'\([a-d]\)', ' ', s)
    s = ''.join(ch if _ud.category(ch)[0] in 'LNM' else ' ' for ch in s)
    return ' '.join(s.split())


def _sh(n):
    w = n.split(' ')
    if len(w) < 3:
        return frozenset([n])
    return frozenset(' '.join(w[i:i + 3]) for i in range(len(w) - 2))


def guarded(R, st):
    tpls = R.build(st)
    if '--capacity' in _sys.argv:
        return tpls
    out = []
    for t in tpls:
        def fn(rng, slot, f=t.fn):
            o = f(rng, slot)
            if not o:
                return o
            txt = o['stem'] + (' ' + ' '.join(sorted(str(x) for x in o['options'])) if o.get('options') else '')
            n = _jsnorm(txt)
            sh = _sh(n)
            lst = _SEEN.setdefault(slot.chapter['id'], [])
            for m, sh2, ln in lst:
                if m == n:
                    return None
                if min(len(n), ln) / max(len(n), ln, 1) < 0.7:
                    continue
                inter = len(sh & sh2)
                if inter / ((len(sh) + len(sh2) - inter) or 1) >= 0.85:
                    return None
            lst.append((n, sh, len(n)))
            return o
        out.append(T(t.c, t.d, fn, t.type, t.style, t.name))
    return out


