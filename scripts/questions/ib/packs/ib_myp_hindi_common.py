def g_choose_form(bank, labels, c='C2', name='g_form', ask=None, marks_tr=2, key_tr='1 अंक सही क्रिया-रूप के लिए, 1 अंक लिंग-वचन की सही अन्विति (और आवश्यकता होने पर ‘ने’) के लिए।'):
    """bank: rows of forms aligned with labels; ask = indices that may be asked for (default all)."""
    ask = list(range(len(labels))) if ask is None else ask

    def gen(kit, key, th):
        def fn(rng, slot):
            row = rng.choice(bank)
            j = rng.choice(ask)
            i = rng.choice([k for k in range(len(labels)) if k != j])
            others = [row[k] for k in range(len(labels)) if k != j]
            if len(set(others + [row[j]])) < 4:
                return None
            return mcq(rng, f'वाक्य “{row[i]}” का {labels[j]} वाला रूप कौन-सा है?', row[j], rng.sample(others, 3),
                       f'{labels[j]}: {row[j]}')
        kit.add(key, c, (1, 4), fn, 'mcq', None, name)

        def ident(rng, slot):
            row = rng.choice(bank)
            j = rng.choice(ask)
            others = [l for k, l in enumerate(labels) if k != j]
            return mcq(rng, f'निम्नलिखित वाक्य में किस रूप/काल का प्रयोग हुआ है?\n“{row[j]}”', labels[j], rng.sample(others, 3),
                       f'“{row[j]}” — {labels[j]}।')
        kit.add(key, 'C1', (1, 3), ident, 'mcq', None, name + '_id')

        def tr(rng, slot):
            row = rng.choice(bank)
            j = rng.choice(ask)
            i = rng.choice([k for k in range(len(labels)) if k != j])
            return dict(stem=f'वाक्य को {labels[j]} में बदलकर लिखिए:\n“{row[i]}”', answer=row[j], type='short', marks=marks_tr,
                        markingKey=f'{row[j]} — {key_tr}')
        kit.add(key, 'C3', (1, 4), tr, 'short', None, name + '_tr')

        def para(rng, slot):
            rows = rng.sample(bank, 3)
            j = rng.choice(ask)
            i = rng.choice([k for k in range(len(labels)) if k != j])
            src = ' '.join(r[i] for r in rows)
            ans = ' '.join(r[j] for r in rows)
            return dict(stem=f'नीचे दिए गए अनुच्छेद के सभी वाक्यों को {labels[j]} में बदलकर फिर से लिखिए:\n“{src}”', answer=ans, type='short',
                        marks=3, markingKey=f'{ans} — प्रत्येक सही रूपांतरित वाक्य के लिए 1 अंक (रूप और अन्विति दोनों सही होने चाहिए)।')
        kit.add(key, 'C3', (3, 5), para, 'short', None, name + '_para')
    return gen


def g_transform(bank, label_a, label_b, c=('C3',), marks=2, both=True, extra_key='', name='g_tr'):
    """bank: list of (a, b). Asks to change a -> b (and b -> a when both)."""
    def gen(kit, key, th):
        def fn(rng, slot):
            a, b = rng.choice(bank)[:2]
            if both and rng.random() < 0.5:
                return dict(stem=f'निम्नलिखित वाक्य को {label_a} में बदलिए:\n“{b}”', answer=a, type='short', marks=marks,
                            markingKey=f'{a} {extra_key}'.strip())
            return dict(stem=f'निम्नलिखित वाक्य को {label_b} में बदलिए:\n“{a}”', answer=b, type='short', marks=marks,
                        markingKey=f'{b} {extra_key}'.strip())
        kit.add(key, c, (1, 4), fn, 'short', None, name)
    return gen


def g_free(prompts, c='C4', marks=6, name='g_free'):
    """prompts: (stem with {topic}, answer). Written production with a grammar focus."""
    def gen(kit, key, th):
        def fn(rng, slot):
            s, a = rng.choice(prompts)
            topic = rng.choice(th['topics'])
            m = marks if slot.d >= 4 else max(4, marks - 2)
            return dict(stem=s.format(topic=topic), answer=a, type='long', marks=m, markingKey=para_key(m, a))
        kit.add(key, c, (2, 5), fn, 'long', None, name)
    return gen


def g_classify(bank, labels, what='शब्द', name='g_cls', c_id='C1', c_why='C2', why=True):
    """bank: (sentence, target word, label[, reason]). MCQ: label of the target; C2: explain; C3: find words of a label."""
    def gen(kit, key, th):
        def fn(rng, slot):
            s, w, lab = rng.choice(bank)[:3]
            others = [l for l in labels if l != lab]
            if len(others) < 3:
                return None
            return mcq(rng, rng.choice([f'वाक्य “{s}” में ‘{w}’ किस प्रकार का {what} है?',
                                        f'“{s}” — इस वाक्य में आए {what} ‘{w}’ का भेद पहचानिए।']), lab, rng.sample(others, 3),
                       f'‘{w}’ — {lab}।')
        kit.add(key, c_id, (1, 3), fn, 'mcq', None, name)
        rs = [r for r in bank if len(r) > 3]
        if why and rs:
            def ex(rng, slot):
                s, w, lab, r = rng.choice(rs)
                return dict(stem=f'“{s}” — इस वाक्य में ‘{w}’ को {lab} क्यों माना जाता है? कारण स्पष्ट कीजिए और इसी भेद का एक और उदाहरण दीजिए।',
                            answer=f'{r} (दूसरा उदाहरण: इसी भेद का कोई सही उदाहरण)', type='explain', marks=2,
                            markingKey=f'1 अंक कारण: {r}; 1 अंक इसी भेद का सही नया उदाहरण।')
            kit.add(key, c_why, (1, 4), ex, 'explain', None, name + '_why')

        def find(rng, slot):
            lab = rng.choice(labels)
            rows = [r for r in bank if r[2] == lab]
            others = [r for r in bank if r[2] != lab]
            if not rows or len(others) < 2:
                return None
            pick = rng.sample(rows, min(2, len(rows))) + rng.sample(others, 2)
            rng.shuffle(pick)
            lines = '\n'.join(f'({i}) {r[0]} — ‘{r[1]}’' for i, r in enumerate(pick, 1))
            right = [f'({i})' for i, r in enumerate(pick, 1) if r[2] == lab]
            return dict(stem=f'नीचे दिए गए वाक्यों में से उन वाक्यों की संख्या लिखिए जिनमें दिया गया {what} {lab} है, और बाकी वाक्यों के {what} का भेद भी लिखिए:\n{lines}',
                        answer=f'{lab}: {", ".join(right)}। ' + '; '.join(f'({i}) {r[2]}' for i, r in enumerate(pick, 1) if r[2] != lab),
                        type='short', marks=3, markingKey='सही वाक्य-संख्याओं के लिए 1 अंक; बाकी प्रत्येक सही भेद के लिए 1 अंक: ' +
                        '; '.join(f'({i}) {r[2]}' for i, r in enumerate(pick, 1)))
        kit.add(key, 'C3', (2, 4), find, 'short', None, name + '_find')
    return gen


def g_pairs(bank, label_b, label_a=None, name='g_pair', c=('C1',), extra=None):
    """bank: (a, b) word pairs, e.g. masculine -> feminine. MCQ for b, reverse MCQ and a short list item."""
    def gen(kit, key, th):
        def fn(rng, slot):
            a, b = rng.choice(bank)
            wrong = [x[1] for x in bank if x[1] != b and x[0] != a]
            ex = [e for e in (extra or {}).get(a, []) if e != b]
            w = (ex + rng.sample(wrong, 3))[:3]
            return mcq(rng, rng.choice([f'‘{a}’ शब्द का {label_b} रूप कौन-सा है?', f'निम्नलिखित में से ‘{a}’ का सही {label_b} चुनिए।']), b, w,
                       f'‘{a}’ का {label_b} — ‘{b}’।')
        kit.add(key, c, (1, 3), fn, 'mcq', None, name)

        def lst(rng, slot):
            rows = rng.sample(bank, 3 if slot.d <= 2 else 4)
            if rng.random() < 0.5 or not label_a:
                return dict(stem=f'निम्नलिखित शब्दों के {label_b} रूप लिखिए: {", ".join(r[0] for r in rows)}।',
                            answer='; '.join(f'{r[0]} — {r[1]}' for r in rows), type='short', marks=len(rows) // 2 + 1,
                            markingKey='प्रत्येक सही रूप के लिए आधा अंक (वर्तनी सहित): ' + '; '.join(f'{r[0]} — {r[1]}' for r in rows))
            return dict(stem=f'निम्नलिखित शब्दों के {label_a} रूप लिखिए: {", ".join(r[1] for r in rows)}।',
                        answer='; '.join(f'{r[1]} — {r[0]}' for r in rows), type='short', marks=len(rows) // 2 + 1,
                        markingKey='प्रत्येक सही रूप के लिए आधा अंक (वर्तनी सहित): ' + '; '.join(f'{r[1]} — {r[0]}' for r in rows))
        kit.add(key, ('C1', 'C3'), (1, 3), lst, 'short', None, name + '_list')
    return gen


def g_correct(bank, name='g_corr', c=('C2', 'C3')):
    """bank: (wrong sentence, right sentence, rule)."""
    def gen(kit, key, th):
        def fn(rng, slot):
            w, r, why = rng.choice(bank)
            if slot.d >= 3 and rng.random() < 0.5:
                return dict(stem=f'एक विद्यार्थी ने लिखा: “{w}”\nइस वाक्य की व्याकरणिक भूल पहचानिए, वाक्य शुद्ध कीजिए और नियम समझाइए।',
                            answer=f'{r} — {why}', type='explain', marks=3,
                            markingKey=f'1 अंक भूल की पहचान, 1 अंक शुद्ध वाक्य ({r}), 1 अंक नियम: {why}', gap='G2')
            return dict(stem=f'वाक्य शुद्ध करके लिखिए:\n“{w}”', answer=r, type='short', marks=2,
                        markingKey=f'{r} — 1 अंक भूल सुधारने पर, 1 अंक पूरे वाक्य की शुद्धता पर। नियम: {why}', gap='G2')
        kit.add(key, c, (1, 4), fn, 'short', None, name)

        def pick(rng, slot):
            w, r, why = rng.choice(bank)
            others = [x[0] for x in bank if x[0] != w]
            if len(others) < 2:
                return None
            wr = rng.sample(others, 2) + [w]
            return mcq(rng, 'निम्नलिखित में से कौन-सा वाक्य व्याकरण की दृष्टि से शुद्ध है?', r, wr, f'शुद्ध वाक्य: {r} — {why}')
        kit.add(key, 'C1', (1, 3), pick, 'mcq', None, name + '_pick')
    return gen


